// Writes ui/.ai/PROGRESS.md: which Symfony back office pages render with the /ui kit, how much of their markup goes
// through <twig:ui:*> components, the kit components, and the findings left by the last screen review of each page.
//
//   node ui/.ai/bin/progress.mjs [--check | --pages-json]
//   --check prints the report without writing it; --pages-json prints the page list (used by the ui-inventory workflow)
import {execSync} from 'node:child_process';
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {basename, dirname, join, relative} from 'node:path';

const root = execSync('git rev-parse --show-toplevel').toString().trim();
const views = join(root, 'src/PrestaShopBundle/Resources/views');
const controllers = join(root, 'src/PrestaShopBundle/Controller/Admin');
const reviewsDir = join(root, 'ui/.ai/reviews');

const walk = (dir, filter) => readdirSync(dir, {withFileTypes: true}).flatMap((entry) => {
  const path = join(dir, entry.name);

  if (entry.isDirectory()) {
    return walk(path, filter);
  }

  return filter(path) ? [path] : [];
});

// A page is a template a back office controller renders
const pages = new Map();
walk(controllers, (path) => path.endsWith('.php')).forEach((controller) => {
  const source = readFileSync(controller, 'utf8');
  for (const match of source.matchAll(/'@PrestaShop\/(Admin\/[^']+\.html\.twig)'/g)) {
    const template = match[1];
    if (!template.includes('/Ui/') && existsSync(join(views, template))) {
      pages.set(template, relative(root, controller));
    }
  }
});

const kitTemplateOf = (template) => {
  const sibling = join(views, dirname(template), 'Ui', basename(template));
  if (existsSync(sibling)) return sibling;
  const source = readFileSync(join(views, template), 'utf8');
  const match = source.match(/extends\s+ui_kit\s*\?\s*'@PrestaShop\/([^']+)'/);

  return match ? join(views, match[1]) : null;
};

// Raw Bootstrap component markup that a <twig:ui:*> component could replace
const rawPattern = /class="[^"]*\b(alert|card|modal|nav-tabs|nav-pills|pagination|badge|dropdown-menu|table|breadcrumb|list-group|toast|accordion)\b/g;
const adoption = (file) => {
  const source = readFileSync(file, 'utf8');

  return {components: (source.match(/<twig:ui:/g) || []).length, raw: (source.match(rawPattern) || []).length};
};

const reviews = existsSync(reviewsDir)
  ? readdirSync(reviewsDir).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(join(reviewsDir, f), 'utf8')))
  : [];

const rows = [...pages.keys()].sort().map((template) => {
  const kit = kitTemplateOf(template);
  const parts = template.split('/');

  return {
    section: parts.slice(1, 3).join(' › '),
    template: template.replace(/^Admin\//, ''),
    kit: kit ? relative(views, kit).replace(/^Admin\//, '') : null,
    ...(kit ? adoption(kit) : {components: 0, raw: 0}),
  };
});

if (process.argv.includes('--pages-json')) {
  console.log(JSON.stringify(rows.map((row) => ({...row, controller: pages.get(`Admin/${row.template}`)}))));
  process.exit(0);
}

const sections = new Map();
rows.forEach((row) => {
  const section = sections.get(row.section) || {pages: 0, kit: 0};
  section.pages += 1;
  section.kit += row.kit ? 1 : 0;
  sections.set(row.section, section);
});

const components = walk(join(root, 'src/PrestaShopBundle/Twig/Component/Ui'), (p) => p.endsWith('.php')).map((p) => basename(p, '.php')).sort();
const stories = existsSync(join(root, 'ui/src/stories/components'))
  ? readdirSync(join(root, 'ui/src/stories/components')).map((f) => f.replace(/\.stories\.js$/, ''))
  : [];

const kitRows = rows.filter((r) => r.kit);
const percent = (n, total) => (total ? `${Math.round((n / total) * 100)}%` : '–');
const today = new Date().toISOString().slice(0, 10);

const lines = [
  '# /ui kit progress',
  '',
  `Generated by \`node ui/.ai/bin/progress.mjs\` on ${today}. Do not edit by hand: change the code or the review files, then regenerate.`,
  '',
  '## Coverage',
  '',
  `**${kitRows.length} of ${rows.length} pages** (${percent(kitRows.length, rows.length)}) render with the kit. A page is a template a back office Symfony controller renders; it is on the kit when it has a \`Ui/\` template.`,
  '',
  '| Section | Pages | On the kit |',
  '|---------|------:|-----------:|',
  ...[...sections.entries()].sort().map(([name, s]) => `| ${name} | ${s.pages} | ${s.kit ? `${s.kit} (${percent(s.kit, s.pages)})` : '–'} |`),
  '',
  '## Pages on the kit',
  '',
  'Adoption counts `<twig:ui:*>` uses against raw Bootstrap component markup (alert, card, modal, table, tabs, badge…) left in the `Ui/` template itself, not in what it includes.',
  '',
  '| Page | Ui template | Components | Raw markup | Last review | Open findings |',
  '|------|-------------|-----------:|-----------:|-------------|---------------|',
  ...kitRows.map((row) => {
    const review = reviews.find((r) => row.template.includes(`/${r.page}.html.twig`) || row.kit.includes(`/${r.page}.html.twig`));
    const open = review ? Object.entries(review.findings).filter(([, n]) => n).map(([s, n]) => `${n} ${s}`).join(', ') || 'none' : '–';

    return `| ${row.template} | ${row.kit} | ${row.components} | ${row.raw} | ${review ? review.date : 'never'} | ${open} |`;
  }),
  '',
  '## Open findings',
  '',
  ...(reviews.length ? reviews.flatMap((review) => [
    `### ${review.page} — ${review.date}`,
    '',
    ...(review.note ? [review.note, ''] : []),
    ...(review.open.length ? review.open.map((f) => `- **${f.severity}** ${f.title} (${f.where})`) : ['None.']),
    '',
  ]) : ['No review recorded yet: the `ui-screen-review` workflow writes them to `ui/.ai/reviews/` when given `reviewsDir`.', '']),
  '## Kit components',
  '',
  `Twig components (${components.length}): ${components.map((c) => `\`ui:${c}\``).join(', ') || 'none'}.`,
  '',
  `Storybook component stories (${stories.length}): ${stories.join(', ')}.`,
  '',
  existsSync(join(root, 'ui/.ai/INVENTORY.md'))
    ? 'The component backlog is in [INVENTORY.md](INVENTORY.md).'
    : 'No inventory yet: run the `ui-inventory` workflow.',
  '',
];

const markdown = lines.join('\n');

if (process.argv.includes('--check')) {
  console.log(markdown);
} else {
  writeFileSync(join(root, 'ui/.ai/PROGRESS.md'), markdown);
  console.log(`ui/.ai/PROGRESS.md: ${kitRows.length}/${rows.length} pages on the kit, ${reviews.length} review(s).`);
}
